/** Resolve a stable UI key. User-written reminder text never passes through this function. */
export function t(key, language = 'zh', vars = {}) {
  const value = translations[language === 'en' ? 'en' : 'zh'][key] ?? translations.zh[key] ?? key;
  return value.replace(/\{(\w+)\}/g, (match, name) => vars[name] === undefined ? match : String(vars[name]));
}

const phraseKeys = new Map(Object.entries(translations.zh).map(([key, value]) => [value, key]));
/** Convenience helper for static text nodes and attributes in the original HTML. */
export function translate(text, language = 'zh') {
  const input = String(text);
  const key = phraseKeys.get(input.trim());
  if (!key) return input;
  return input.replace(input.trim(), t(key, language));
}
